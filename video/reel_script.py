    subprocess.run(['RHVoice-test', '-p', VOICE, '-r', '138', '-o', f], input=tts.encode(), check=True)
    with wave.open(f) as w:
        d = w.getnframes() / w.getframerate()
    out.append({"id": sid, "caption": cap, "file": f.replace('public/', ''), "start": round(t, 3), "dur": round(d, 3)})
